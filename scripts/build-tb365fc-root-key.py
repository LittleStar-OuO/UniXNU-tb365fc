#!/usr/bin/env python3
"""Build build/tb365fc-root-key/libTB365FCRootKey.a, the XNU_VERIFIED_ROOT_ARCHIVE of tb365fc.

It carries the owner anchor and the VerifiedRoot code that the owner root chain and NativeUfs use:
  verified_root_key               the 395-byte anchor of package/root-key/owner-public.pem ("VROOTKEY", modulus, 65537)
  verified_root_manifest(_bytes)  the self-test envelope of package/root-key/selftest.json
  tb365fc_selftest_data(_bytes)   the two blocks that envelope signs
  vr_open, vr_verify_block        kits/VerifiedRoot/src/verified_root.c
  vr_xnu_crypto                   kits/VerifiedRoot/adapters/xnu_crypto.c
  native_verified_root_probe      package/TB365FCRootProbe.c (self-test of the anchor, XNU_VERIFIED_ROOT_PROBE)
The OS and SystemOS envelopes are not in the kernel: NativeUfs reads them from userdata
(scripts/make-tb365fc-root-policy.py). Compiled with the kernel's own record for bsd_init.c, as
UniXNU scripts/build-verified-root-probe.py does.
"""
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def package_root():
    # The device package is package/ in the device repository and kits/tb365fc in the assembled tree.
    for candidate in (ROOT / 'kits/tb365fc', ROOT / 'package'):
        if (candidate / 'root-key/owner-public.pem').is_file():
            return candidate
    raise SystemExit('package/root-key/owner-public.pem not found')


KIT = package_root()
out = ROOT / 'build/tb365fc-root-key'
out.mkdir(parents=True, exist_ok=True)
spec = importlib.util.spec_from_file_location('vr_manifest', ROOT / 'kits/VerifiedRoot/tools/manifest.py')
manifest = importlib.util.module_from_spec(spec)
spec.loader.exec_module(manifest)
anchor = manifest.public_anchor(KIT / 'root-key/owner-public.pem')
selftest = json.loads((KIT / 'root-key/selftest.json').read_text())
envelope, data = bytes.fromhex(selftest['envelope']), bytes.fromhex(selftest['data'])
if envelope[120:152] != hashlib.sha256(anchor).digest():
    raise SystemExit('package/root-key/selftest.json was not signed with package/root-key/owner-public.pem')
(out / 'anchor.bin').write_bytes(anchor)
(out / 'selftest-envelope.bin').write_bytes(envelope)
(out / 'selftest-data.bin').write_bytes(data)
assembly = out / 'inputs.S'
assembly.write_text(f'''// Generated by scripts/build-tb365fc-root-key.py
.section __DATA_CONST,__const
.balign 8
.globl _verified_root_key
_verified_root_key:
.incbin "{out / 'anchor.bin'}"
.balign 8
.globl _verified_root_manifest, _verified_root_manifest_bytes
_verified_root_manifest:
.incbin "{out / 'selftest-envelope.bin'}"
.balign 8
_verified_root_manifest_bytes:
.quad {len(envelope)}
.globl _tb365fc_selftest_data, _tb365fc_selftest_data_bytes
_tb365fc_selftest_data:
.incbin "{out / 'selftest-data.bin'}"
.balign 8
_tb365fc_selftest_data_bytes:
.quad {len(data)}
''')
recipe = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/bsd/DEVELOPMENT/bsd_init.o.json'
record = json.loads(recipe.read_text().strip().rstrip(','))
objects = []
for source in (ROOT / 'kits/VerifiedRoot/src/verified_root.c', ROOT / 'kits/VerifiedRoot/adapters/xnu_crypto.c',
               KIT / 'TB365FCRootProbe.c'):
    destination = out / (source.stem + '.o')
    arguments, command, index = record['arguments'], [], 0
    while index < len(arguments):
        value = arguments[index]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(destination)]
            index += 1
        elif value in ('-MF', '-MJ'):
            index += 1
        elif value not in ('-MD', '-MP'):
            command.append(value)
        index += 1
    # The kernel record may name export header directories that only a later pass creates.
    # The Linux toolchain is upstream clang, which implements warnings that Apple's clang
    # does not (unsafe-buffer-usage, shadow-header); the BSD record enables -Werror with
    # them, so switch those two back off for these C sources.
    command += ['-I' + str(ROOT / 'kits/VerifiedRoot/include'), '-Werror', '-Wno-missing-include-dirs',
                '-Wno-unsafe-buffer-usage', '-Wno-shadow-header']
    result = subprocess.run(command, cwd=record['directory'], capture_output=True, text=True)
    (out / (source.stem + '.log')).write_text(result.stdout + result.stderr)
    if result.returncode:
        raise SystemExit(result.stderr[-3500:])
    objects.append(destination)
sdk = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
subprocess.run(['xcrun', 'clang', '-target', 'arm64-apple-ios17.0', '-isysroot', sdk, '-c', assembly, '-o', out / 'inputs.o'],
               check=True)
objects.append(out / 'inputs.o')
for obj in objects:
    if struct.unpack_from('<4I', obj.read_bytes()) != (0xfeedfacf, 0x100000c, 0, 1):
        raise SystemExit(f'{obj}: unexpected object format')
archive = out / 'libTB365FCRootKey.a'
archive.unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', archive, *objects], check=True)
(out / 'root-key.json').write_text(json.dumps(dict(
    trusted_key_sha256=hashlib.sha256(anchor).hexdigest(), selftest_envelope_sha256=hashlib.sha256(envelope).hexdigest(),
    archive_sha256=hashlib.sha256(archive.read_bytes()).hexdigest()), indent=2) + '\n')
print(f'tb365fc root key archive: {archive} (anchor sha256 {hashlib.sha256(anchor).hexdigest()})')
